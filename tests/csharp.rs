/// Gets the public getter of the schema field with the `name`, which reads the `expression`.
fn getter(name: &str, csharp_type: CSharpType, expression: &str) -> Property {
    Property::from((name, csharp_type))
        .with_access(Access::Public)
        .with_expression(expression)
}

/// Gets the doc comment of the getter of the schema field with the `name`.
fn getter_comment(name: &str) -> String {
    format!(" Gets the field: <c>{}</c>.", name)
}

/// A struct is a sealed class with a getter for each field, in a file of its own.
#[test]
fn struct_file() {
    let int: CSharpType = CSharpPrimitive::SignedInt32.into();
    let byte: CSharpType = CSharpPrimitive::UnsignedInt8.into();

    let constructor: Constructor = Constructor::from("Point")
        .with_comment(" Creates the point.")
        .with_access(Access::Public)
        .with_param(("x", int.clone()))
        .with_param(("y", int.clone()))
        .with_semi("_x = x")
        .with_semi("_y = y");

    let invalid: Block = Block::default()
        .with_semi("throw new ArgumentException(\"The bytes are not a point.\", nameof(bytes))");
    let decode: Function = Function::from(
        Signature::from("Decode")
            .with_param((
                "bytes",
                CSharpType::from("ReadOnlySpan").with_generic(byte.clone()),
            ))
            .with_result("Point"),
    )
    .with_comment(" Decodes the point from the bytes.")
    .with_access(Access::Public)
    .with_modifier(Modifier::Static)
    .with_statement(IfStatement::from("bytes.Length != 8").with_success_statements(invalid))
    .with_statement(VarInit::from((
        ("x", int.clone()),
        "BinaryPrimitives.ReadInt32LittleEndian(bytes)",
    )))
    .with_statement(VarInit::from((
        ("y", int.clone()),
        "BinaryPrimitives.ReadInt32LittleEndian(bytes.Slice(4))",
    )))
    .with_semi("return new Point(x, y)");

    let encode: Function = Function::from(Signature::from("Encode").with_result(byte.to_array()))
        .with_comment(" Encodes the point.")
        .with_access(Access::Public)
        .with_statement(VarInit::from((("bytes", "byte[]"), "new byte[8]")))
        .with_semi("BinaryPrimitives.WriteInt32LittleEndian(bytes, _x)")
        .with_semi("BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(4), _y)")
        .with_semi("return bytes");

    let equals: Function = Function::from(
        Signature::from("Equals")
            .with_param(("other", CSharpType::from("Point").to_nullable()))
            .with_result(CSharpPrimitive::Boolean),
    )
    .with_access(Access::Public)
    .with_semi("return other is not null && _x == other._x && _y == other._y");
    let equals_object: Function = Function::from(
        Signature::from("Equals")
            .with_param((
                "obj",
                CSharpType::from(CSharpPrimitive::Object).to_nullable(),
            ))
            .with_result(CSharpPrimitive::Boolean),
    )
    .with_access(Access::Public)
    .with_modifier(Modifier::Override)
    .with_semi("return Equals(obj as Point)");
    let get_hash_code: Function =
        Function::from(Signature::from("GetHashCode").with_result(int.clone()))
            .with_access(Access::Public)
            .with_modifier(Modifier::Override)
            .with_semi("return HashCode.Combine(_x, _y)");

    let mut point: Class = Class::from("Point")
        .with_comment(" A point on a grid.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Sealed)
        .with_base_type("IPointView")
        .with_base_type(CSharpType::from("IEquatable").with_generic("Point"))
        .with_constructor(constructor)
        .with_function(decode)
        .with_function(encode)
        .with_function(equals)
        .with_function(equals_object)
        .with_function(get_hash_code);
    for (field, property) in [("_x", "X"), ("_y", "Y")] {
        point.add_field(
            Field::from((field, int.clone()))
                .with_access(Access::Private)
                .with_modifier(Modifier::Readonly),
        );
        point.add_property(
            getter(property, int.clone(), field)
                .with_comment(getter_comment(&property.to_lowercase())),
        );
    }

    let file: Block = Block::default()
        .with_literal("// <auto-generated/>")
        .with_literal("#nullable enable")
        .with_empty_line()
        .with_semi("using System")
        .with_semi("using System.Buffers.Binary")
        .with_empty_line()
        .with_semi("namespace Geometry")
        .with_empty_line()
        .with_statement(point);

    assert_eq!(
        file.to_code(),
        "\
// <auto-generated/>
#nullable enable

using System;
using System.Buffers.Binary;

namespace Geometry;

/// <summary>
/// A point on a grid.
/// </summary>
public sealed class Point : IPointView, IEquatable<Point>
{
    private readonly int _x;
    private readonly int _y;

    /// <summary>
    /// Creates the point.
    /// </summary>
    public Point(int x, int y)
    {
        _x = x;
        _y = y;
    }

    /// <summary>
    /// Gets the field: <c>x</c>.
    /// </summary>
    public int X => _x;

    /// <summary>
    /// Gets the field: <c>y</c>.
    /// </summary>
    public int Y => _y;

    /// <summary>
    /// Decodes the point from the bytes.
    /// </summary>
    public static Point Decode(ReadOnlySpan<byte> bytes)
    {
        if (bytes.Length != 8)
        {
            throw new ArgumentException(\"The bytes are not a point.\", nameof(bytes));
        }
        int x = BinaryPrimitives.ReadInt32LittleEndian(bytes);
        int y = BinaryPrimitives.ReadInt32LittleEndian(bytes.Slice(4));
        return new Point(x, y);
    }

    /// <summary>
    /// Encodes the point.
    /// </summary>
    public byte[] Encode()
    {
        byte[] bytes = new byte[8];
        BinaryPrimitives.WriteInt32LittleEndian(bytes, _x);
        BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(4), _y);
        return bytes;
    }

    public bool Equals(Point? other)
    {
        return other is not null && _x == other._x && _y == other._y;
    }

    public override bool Equals(object? obj)
    {
        return Equals(obj as Point);
    }

    public override int GetHashCode()
    {
        return HashCode.Combine(_x, _y);
    }
}
"
    );
}

/// A message is a class with an optional property for each field.
#[test]
fn message() {
    let fields: [(&str, CSharpType); 3] = [
        ("Name", CSharpPrimitive::String.into()),
        ("Age", CSharpPrimitive::UnsignedInt32.into()),
        (
            "Emails",
            CSharpType::from("List").with_generic(CSharpPrimitive::String),
        ),
    ];
    let mut person: Class = Class::from("Person")
        .with_comment(" A person.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Sealed);
    for (name, csharp_type) in fields {
        person.add_property(
            Property::from((name, csharp_type.to_nullable()))
                .with_comment(format!(" The field: <c>{}</c>.", name.to_lowercase()))
                .with_access(Access::Public)
                .with_accessor("get")
                .with_accessor("set"),
        );
    }

    assert_eq!(
        person.to_code(),
        "\
/// <summary>
/// A person.
/// </summary>
public sealed class Person
{
    /// <summary>
    /// The field: <c>name</c>.
    /// </summary>
    public string? Name { get; set; }

    /// <summary>
    /// The field: <c>age</c>.
    /// </summary>
    public uint? Age { get; set; }

    /// <summary>
    /// The field: <c>emails</c>.
    /// </summary>
    public List<string>? Emails { get; set; }
}
"
    );
}

/// An enum is a C# enum of its tag numbers. A C# enum also holds the numbers it has no case for.
#[test]
fn enumeration() {
    let cases: [(&str, u16); 2] = [("Red", 1), ("Green", 2)];
    let mut color: Enum = Enum::from("Color")
        .with_comment(" A color.")
        .with_comment(" A tag number with no case is a color the enum doesn't know.")
        .with_access(Access::Public)
        .with_underlying_type(CSharpPrimitive::UnsignedInt16);
    let mut name_of: SwitchStatement = SwitchStatement::from("color");
    for (name, tag_number) in cases {
        color.add_case(
            EnumCase::from(name)
                .with_comment(format!(" The case: <c>{}</c>.", name))
                .with_value(tag_number.to_string()),
        );
        name_of.add_switch_case(
            SwitchCase::from(format!("Color.{}", name))
                .with_semi(format!("return \"{}\"", name))
                .with_break(false),
        );
    }
    name_of.add_switch_case(
        SwitchCase::default()
            .with_semi("return null")
            .with_break(false),
    );

    let extensions: Class = Class::from("ColorExtensions")
        .with_comment(" The functions of a <see cref=\"Color\"/>.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Static)
        .with_function(
            Function::from(
                Signature::from("Name")
                    .with_param(("color", "this Color"))
                    .with_result(CSharpType::from(CSharpPrimitive::String).to_nullable()),
            )
            .with_comment(" Gets the name of the color's case.")
            .with_comment(" Returns null if the enum doesn't know the color.")
            .with_access(Access::Public)
            .with_modifier(Modifier::Static)
            .with_statement(name_of),
        );

    let code: String = Block::default()
        .with_statement(color)
        .with_empty_line()
        .with_statement(extensions)
        .to_code();
    assert_eq!(
        code,
        "\
/// <summary>
/// A color.
/// A tag number with no case is a color the enum doesn't know.
/// </summary>
public enum Color : ushort
{
    /// <summary>
    /// The case: <c>Red</c>.
    /// </summary>
    Red = 1,

    /// <summary>
    /// The case: <c>Green</c>.
    /// </summary>
    Green = 2,
}

/// <summary>
/// The functions of a <see cref=\"Color\"/>.
/// </summary>
public static class ColorExtensions
{
    /// <summary>
    /// Gets the name of the color's case.
    /// Returns null if the enum doesn't know the color.
    /// </summary>
    public static string? Name(this Color color)
    {
        switch (color)
        {
            case Color.Red:
                return \"Red\";
            case Color.Green:
                return \"Green\";
            default:
                return null;
        }
    }
}
"
    );
}

/// A variant is an abstract record with a nested sealed record for each case.
#[test]
fn variant() {
    let tag_number: Var = Var::from(("TagNumber", CSharpPrimitive::UnsignedInt16));
    let case = |name: &str, comment: &str, tag_number_expression: &str| -> Record {
        Record::from(name)
            .with_comment(comment)
            .with_access(Access::Public)
            .with_modifier(Modifier::Sealed)
            .with_base_type("Shape")
            .with_property(
                Property::from(tag_number.clone())
                    .with_access(Access::Public)
                    .with_modifier(Modifier::Override)
                    .with_expression(tag_number_expression),
            )
    };

    let shape: Record = Record::from("Shape")
        .with_comment(" A shape.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Abstract)
        .with_constructor(Constructor::from("Shape").with_access(Access::Private))
        .with_property(
            Property::from(tag_number.clone())
                .with_comment(" Gets the tag number of the case.")
                .with_access(Access::Public)
                .with_modifier(Modifier::Abstract),
        )
        .with_nested_type(
            case("Circle", " The case: <c>Circle</c>.", "1")
                .with_param(("Value", CSharpPrimitive::Float64)),
        )
        .with_nested_type(
            case("Label", " The case: <c>Label</c>.", "2")
                .with_param(("Value", CSharpPrimitive::String)),
        )
        .with_nested_type(
            case(
                "Unrecognized",
                " A case the variant doesn't know.",
                "Number",
            )
            .with_param(("Number", CSharpPrimitive::UnsignedInt16))
            .with_param((
                "Bytes",
                CSharpType::from(CSharpPrimitive::UnsignedInt8).to_array(),
            )),
        );

    assert_eq!(
        shape.to_code(),
        "\
/// <summary>
/// A shape.
/// </summary>
public abstract record Shape
{
    private Shape()
    {
    }

    /// <summary>
    /// Gets the tag number of the case.
    /// </summary>
    public abstract ushort TagNumber { get; }

    /// <summary>
    /// The case: <c>Circle</c>.
    /// </summary>
    public sealed record Circle(double Value) : Shape
    {
        public override ushort TagNumber => 1;
    }

    /// <summary>
    /// The case: <c>Label</c>.
    /// </summary>
    public sealed record Label(string Value) : Shape
    {
        public override ushort TagNumber => 2;
    }

    /// <summary>
    /// A case the variant doesn't know.
    /// </summary>
    public sealed record Unrecognized(ushort Number, byte[] Bytes) : Shape
    {
        public override ushort TagNumber => Number;
    }
}
"
    );
}

/// A view is an interface of getters. A struct over the encoded bytes is one form of it.
#[test]
fn view() {
    let int: CSharpType = CSharpPrimitive::SignedInt32.into();
    let bytes: CSharpType = CSharpType::from(CSharpPrimitive::UnsignedInt8).to_array();
    let memory: CSharpType =
        CSharpType::from("ReadOnlyMemory").with_generic(CSharpPrimitive::UnsignedInt8);
    let encode: Signature = Signature::from("Encode").with_result(bytes);

    let view: Interface = Interface::from("IPointView")
        .with_comment(" The fields of any form of a <see cref=\"Point\"/>.")
        .with_access(Access::Public)
        .with_property(Property::from(("X", int.clone())).with_comment(getter_comment("x")))
        .with_property(Property::from(("Y", int.clone())).with_comment(getter_comment("y")))
        .with_signature_dec(SignatureDec::from(encode.clone()).with_comment(" Encodes the point."));

    let point_ref: Struct = Struct::from("PointRef")
        .with_comment(" A point over its encoded bytes.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Readonly)
        .with_base_type("IPointView")
        .with_field(
            Field::from(("_bytes", memory.clone()))
                .with_access(Access::Private)
                .with_modifier(Modifier::Readonly),
        )
        .with_constructor(
            Constructor::from("PointRef")
                .with_comment(" Creates the point over the bytes.")
                .with_access(Access::Public)
                .with_param(("bytes", memory))
                .with_semi("_bytes = bytes"),
        )
        .with_property(getter(
            "X",
            int.clone(),
            "BinaryPrimitives.ReadInt32LittleEndian(_bytes.Span)",
        ))
        .with_property(getter(
            "Y",
            int,
            "BinaryPrimitives.ReadInt32LittleEndian(_bytes.Span.Slice(4))",
        ))
        .with_function(
            Function::from(encode)
                .with_access(Access::Public)
                .with_semi("return _bytes.ToArray()"),
        );

    let code: String = Block::default()
        .with_statement(view)
        .with_empty_line()
        .with_statement(point_ref)
        .to_code();
    assert_eq!(
        code,
        "\
/// <summary>
/// The fields of any form of a <see cref=\"Point\"/>.
/// </summary>
public interface IPointView
{
    /// <summary>
    /// Gets the field: <c>x</c>.
    /// </summary>
    int X { get; }

    /// <summary>
    /// Gets the field: <c>y</c>.
    /// </summary>
    int Y { get; }

    /// <summary>
    /// Encodes the point.
    /// </summary>
    byte[] Encode();
}

/// <summary>
/// A point over its encoded bytes.
/// </summary>
public readonly struct PointRef : IPointView
{
    private readonly ReadOnlyMemory<byte> _bytes;

    /// <summary>
    /// Creates the point over the bytes.
    /// </summary>
    public PointRef(ReadOnlyMemory<byte> bytes)
    {
        _bytes = bytes;
    }

    public int X => BinaryPrimitives.ReadInt32LittleEndian(_bytes.Span);
    public int Y => BinaryPrimitives.ReadInt32LittleEndian(_bytes.Span.Slice(4));

    public byte[] Encode()
    {
        return _bytes.ToArray();
    }
}
"
    );
}

/// A service is an interface with an async method for each call, & a function that routes to it.
#[test]
fn service() {
    let calls: [(&str, &str); 2] = [
        ("Greet", " Greets the person."),
        ("Farewell", " Says goodbye to the person."),
    ];
    let bytes: CSharpType = CSharpType::from(CSharpPrimitive::UnsignedInt8).to_array();
    let mut greeter: Interface = Interface::from("IGreeter")
        .with_comment(" A service that greets people.")
        .with_access(Access::Public);
    let mut route: SwitchStatement = SwitchStatement::from("call");
    for (call, comment) in calls {
        greeter.add_signature_dec(
            SignatureDec::from(
                Signature::from(format!("{}Async", call))
                    .with_param(("request", "Person"))
                    .with_result(CSharpType::from("Task").with_generic("Greeting")),
            )
            .with_comment(comment),
        );
        route.add_switch_case(
            SwitchCase::from(format!("\"{}\"", call))
                .with_semi(format!(
                    "return (await service.{}Async(Person.Decode(request))).Encode()",
                    call
                ))
                .with_break(false),
        );
    }
    let unknown: &str =
        "throw new ArgumentException(\"The service has no such call.\", nameof(call))";
    route.add_switch_case(SwitchCase::default().with_semi(unknown).with_break(false));

    let router: Class = Class::from("GreeterRouter")
        .with_comment(" Routes the requests of a <see cref=\"IGreeter\"/>.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Static)
        .with_function(
            Function::from(
                Signature::from("RouteAsync")
                    .with_param(("service", "IGreeter"))
                    .with_param(("call", CSharpPrimitive::String))
                    .with_param(("request", bytes.clone()))
                    .with_result(CSharpType::from("Task").with_generic(bytes)),
            )
            .with_comment(" Routes the encoded request to its call.")
            .with_comment(" Returns the encoded response.")
            .with_access(Access::Public)
            .with_modifier(Modifier::Async)
            .with_modifier(Modifier::Static)
            .with_statement(route),
        );

    let code: String = Block::default()
        .with_statement(greeter)
        .with_empty_line()
        .with_statement(router)
        .to_code();
    assert_eq!(
        code,
        "\
/// <summary>
/// A service that greets people.
/// </summary>
public interface IGreeter
{
    /// <summary>
    /// Greets the person.
    /// </summary>
    Task<Greeting> GreetAsync(Person request);

    /// <summary>
    /// Says goodbye to the person.
    /// </summary>
    Task<Greeting> FarewellAsync(Person request);
}

/// <summary>
/// Routes the requests of a <see cref=\"IGreeter\"/>.
/// </summary>
public static class GreeterRouter
{
    /// <summary>
    /// Routes the encoded request to its call.
    /// Returns the encoded response.
    /// </summary>
    public static async Task<byte[]> RouteAsync(IGreeter service, string call, byte[] request)
    {
        switch (call)
        {
            case \"Greet\":
                return (await service.GreetAsync(Person.Decode(request))).Encode();
            case \"Farewell\":
                return (await service.FarewellAsync(Person.Decode(request))).Encode();
            default:
                throw new ArgumentException(\"The service has no such call.\", nameof(call));
        }
    }
}
"
    );
}
