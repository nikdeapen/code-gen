use code_gen::java::*;
use code_gen::*;

/// The type of an encoding.
fn bytes() -> JavaType {
    JavaType::from(JavaPrimitive::Byte).to_array()
}

/// A struct is a final class with a constructor, getters, setters, decoding, equality & ordering.
#[test]
fn struct_class() {
    let mut class: Class = Class::from("Point")
        .with_comment(" A point on a grid.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Final)
        .with_implements("PointView")
        .with_implements(JavaType::from("Comparable").with_generic("Point"));
    let mut constructor: Constructor = Constructor::from("Point")
        .with_comment(" Creates a point.")
        .with_access(Access::Public);
    for (name, setter) in [("x", "setX"), ("y", "setY")] {
        class.add_field(Field::from((name, JavaPrimitive::Int)).with_access(Access::Private));
        constructor.add_param((name, JavaPrimitive::Int));
        constructor.add_semi(format!("this.{name} = {name}"));
        class.add_function(
            Function::from(Signature::from(name).with_result(JavaPrimitive::Int))
                .with_comment(format!(" Gets the field: {{@code {name}}}."))
                .with_annotation("Override")
                .with_access(Access::Public)
                .with_semi(format!("return this.{name}")),
        );
        class.add_function(
            Function::from(Signature::from(setter).with_param((name, JavaPrimitive::Int)))
                .with_comment(format!(" Sets the field: {{@code {name}}}."))
                .with_access(Access::Public)
                .with_semi(format!("this.{name} = {name}")),
        );
    }
    class.add_constructor(constructor);
    class.add_function(
        Function::from(
            Signature::from("decode")
                .with_param(("bytes", bytes()))
                .with_result("Point")
                .with_throws("DecodeException"),
        )
        .with_comment(" Decodes the struct from the bytes.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Static)
        .with_statement(
            IfStatement::from("bytes.length != 8").with_success_statements(
                Block::default().with_semi("throw new DecodeException(\"A Point is 8 bytes.\")"),
            ),
        )
        .with_semi("ByteBuffer in = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN)")
        .with_semi("return new Point(in.getInt(), in.getInt())"),
    );
    class.add_function(
        Function::from(
            Signature::from("equals")
                .with_param(("other", "Object"))
                .with_result(JavaPrimitive::Boolean),
        )
        .with_annotation("Override")
        .with_access(Access::Public)
        .with_semi("return other instanceof Point point && this.x == point.x && this.y == point.y"),
    );
    class.add_function(
        Function::from(Signature::from("hashCode").with_result(JavaPrimitive::Int))
            .with_annotation("Override")
            .with_access(Access::Public)
            .with_semi("return Objects.hash(this.x, this.y)"),
    );
    class.add_function(
        Function::from(
            Signature::from("compareTo")
                .with_param(("other", "Point"))
                .with_result(JavaPrimitive::Int),
        )
        .with_annotation("Override")
        .with_access(Access::Public)
        .with_semi("int result = Integer.compareUnsigned(this.x, other.x)")
        .with_statement(
            IfStatement::from("result != 0")
                .with_success_statements(Block::default().with_semi("return result")),
        )
        .with_semi("return Integer.compareUnsigned(this.y, other.y)"),
    );
    let file: Block = Block::default()
        .with_literal("// DO NOT EDIT: This file was generated by the ProtoPacket compiler.")
        .with_empty_line()
        .with_semi("package types")
        .with_empty_line()
        .with_semi("import java.nio.ByteBuffer")
        .with_semi("import java.nio.ByteOrder")
        .with_semi("import java.util.Objects")
        .with_empty_line()
        .with_statement(class);

    assert_eq!(
        file.to_code(),
        "\
// DO NOT EDIT: This file was generated by the ProtoPacket compiler.

package types;

import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.util.Objects;

/**
 * A point on a grid.
 */
public final class Point implements PointView, Comparable<Point> {
    private int x;
    private int y;

    /**
     * Creates a point.
     */
    public Point(int x, int y) {
        this.x = x;
        this.y = y;
    }

    /**
     * Gets the field: {@code x}.
     */
    @Override
    public int x() {
        return this.x;
    }

    /**
     * Sets the field: {@code x}.
     */
    public void setX(int x) {
        this.x = x;
    }

    /**
     * Gets the field: {@code y}.
     */
    @Override
    public int y() {
        return this.y;
    }

    /**
     * Sets the field: {@code y}.
     */
    public void setY(int y) {
        this.y = y;
    }

    /**
     * Decodes the struct from the bytes.
     */
    public static Point decode(byte[] bytes) throws DecodeException {
        if (bytes.length != 8) {
            throw new DecodeException(\"A Point is 8 bytes.\");
        }
        ByteBuffer in = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN);
        return new Point(in.getInt(), in.getInt());
    }

    @Override
    public boolean equals(Object other) {
        return other instanceof Point point && this.x == point.x && this.y == point.y;
    }

    @Override
    public int hashCode() {
        return Objects.hash(this.x, this.y);
    }

    @Override
    public int compareTo(Point other) {
        int result = Integer.compareUnsigned(this.x, other.x);
        if (result != 0) {
            return result;
        }
        return Integer.compareUnsigned(this.y, other.y);
    }
}
"
    );
}

/// A message is a final class with fields that can be null.
#[test]
fn message_class() {
    let fields: [(&str, &str, JavaType); 2] = [
        (
            "age",
            "setAge",
            JavaType::from(JavaPrimitive::Int).to_boxed(),
        ),
        (
            "scores",
            "setScores",
            JavaType::from("java.util.List").with_generic(JavaPrimitive::Int),
        ),
    ];
    let mut class: Class = Class::from("Person")
        .with_comment(" A person.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Final);
    for (name, setter, java_type) in fields {
        class.add_field(Field::from((name, java_type.clone())).with_access(Access::Private));
        class.add_function(
            Function::from(Signature::from(name).with_result(java_type.clone()))
                .with_comment(format!(" Gets the field: {{@code {name}}}."))
                .with_access(Access::Public)
                .with_semi(format!("return this.{name}")),
        );
        class.add_function(
            Function::from(
                Signature::from(setter)
                    .with_param((name, java_type))
                    .with_result("Person"),
            )
            .with_comment(format!(" Sets the field: {{@code {name}}}."))
            .with_access(Access::Public)
            .with_semi(format!("this.{name} = {name}"))
            .with_semi("return this"),
        );
    }
    class.add_function(
        Function::from(Signature::from("encodeTo").with_param(("out", "java.nio.ByteBuffer")))
            .with_comment(" Appends the encoding of the message to the bytes.")
            .with_access(Access::Public)
            .with_statement(
                IfStatement::from("this.age != null").with_success_statements(
                    Block::default()
                        .with_semi("out.putShort((short) 1)")
                        .with_semi("out.putInt(this.age)"),
                ),
            )
            .with_statement(
                IfStatement::from("this.scores != null").with_success_statements(
                    Block::default()
                        .with_semi("out.putShort((short) 2)")
                        .with_statement(
                            ForLoop::from("int score : this.scores").with_semi("out.putInt(score)"),
                        ),
                ),
            ),
    );

    assert_eq!(
        class.to_code(),
        "\
/**
 * A person.
 */
public final class Person {
    private Integer age;
    private java.util.List<Integer> scores;

    /**
     * Gets the field: {@code age}.
     */
    public Integer age() {
        return this.age;
    }

    /**
     * Sets the field: {@code age}.
     */
    public Person setAge(Integer age) {
        this.age = age;
        return this;
    }

    /**
     * Gets the field: {@code scores}.
     */
    public java.util.List<Integer> scores() {
        return this.scores;
    }

    /**
     * Sets the field: {@code scores}.
     */
    public Person setScores(java.util.List<Integer> scores) {
        this.scores = scores;
        return this;
    }

    /**
     * Appends the encoding of the message to the bytes.
     */
    public void encodeTo(java.nio.ByteBuffer out) {
        if (this.age != null) {
            out.putShort((short) 1);
            out.putInt(this.age);
        }
        if (this.scores != null) {
            out.putShort((short) 2);
            for (int score : this.scores) {
                out.putInt(score);
            }
        }
    }
}
"
    );
}

/// An enum is a sealed interface, since a Java enum can't hold an unrecognized tag number.
#[test]
fn enum_with_an_unrecognized_case() {
    let mut known: Enum = Enum::from("Known")
        .with_comment(" The cases the enum knows.")
        .with_implements("Color")
        .with_field(
            Field::from(("tagNumber", JavaPrimitive::Int))
                .with_access(Access::Private)
                .with_modifier(Modifier::Final),
        )
        .with_constructor(
            Constructor::from("Known")
                .with_param(("tagNumber", JavaPrimitive::Int))
                .with_semi("this.tagNumber = tagNumber"),
        )
        .with_function(
            Function::from(Signature::from("tagNumber").with_result(JavaPrimitive::Int))
                .with_annotation("Override")
                .with_access(Access::Public)
                .with_semi("return this.tagNumber"),
        );
    let mut cases: SwitchStatement = SwitchStatement::from("tagNumber").with_return(true);
    for (name, comment, tag_number) in [("RED", " Red.", 1), ("GREEN", " Green.", 2)] {
        known.add_constant(
            EnumConstant::from(name)
                .with_comment(comment)
                .with_argument(tag_number.to_string()),
        );
        cases.add_switch_case(
            SwitchCase::from(tag_number.to_string()).with_expression(format!("Known.{name}")),
        );
    }
    cases.add_switch_case(SwitchCase::default().with_expression("new Unrecognized(tagNumber)"));
    let interface: Interface = Interface::from("Color")
        .with_comment(" A color.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Sealed)
        .with_signature_dec(
            SignatureDec::from(Signature::from("tagNumber").with_result(JavaPrimitive::Int))
                .with_comment(" Gets the tag number."),
        )
        .with_function(
            Function::from(
                Signature::from("fromTagNumber")
                    .with_param(("tagNumber", JavaPrimitive::Int))
                    .with_result("Color"),
            )
            .with_comment(" Gets the case with the tag number.")
            .with_modifier(Modifier::Static)
            .with_statement(cases),
        )
        .with_nested_type(known)
        .with_nested_type(
            Record::from("Unrecognized")
                .with_comment(" A tag number the enum doesn't know.")
                .with_param(("tagNumber", JavaPrimitive::Int))
                .with_implements("Color"),
        );

    assert_eq!(
        interface.to_code(),
        "\
/**
 * A color.
 */
public sealed interface Color {
    /**
     * Gets the tag number.
     */
    int tagNumber();

    /**
     * Gets the case with the tag number.
     */
    static Color fromTagNumber(int tagNumber) {
        return switch (tagNumber) {
            case 1 -> Known.RED;
            case 2 -> Known.GREEN;
            default -> new Unrecognized(tagNumber);
        };
    }

    /**
     * The cases the enum knows.
     */
    enum Known implements Color {
        /**
         * Red.
         */
        RED(1),

        /**
         * Green.
         */
        GREEN(2);

        private final int tagNumber;

        Known(int tagNumber) {
            this.tagNumber = tagNumber;
        }

        @Override
        public int tagNumber() {
            return this.tagNumber;
        }
    }

    /**
     * A tag number the enum doesn't know.
     */
    record Unrecognized(int tagNumber) implements Color {}
}
"
    );
}

/// A variant is a sealed interface with a nested record for each case.
#[test]
fn variant() {
    let cases: [(&str, &str, JavaType, &str); 2] = [
        (
            "Circle",
            "circle",
            JavaType::from(JavaPrimitive::Double),
            "out.putDouble(circle.value())",
        ),
        (
            "Label",
            "label",
            JavaType::from("String"),
            "out.put(label.value().getBytes(java.nio.charset.StandardCharsets.UTF_8))",
        ),
    ];
    let mut interface: Interface = Interface::from("Shape")
        .with_comment(" A shape.")
        .with_access(Access::Public)
        .with_modifier(Modifier::Sealed)
        .with_signature_dec(
            SignatureDec::from(Signature::from("tagNumber").with_result(JavaPrimitive::Int))
                .with_comment(" Gets the tag number of the case."),
        );
    let mut encode: SwitchStatement = SwitchStatement::from("this");
    for (index, (name, var, java_type, write)) in cases.into_iter().enumerate() {
        interface.add_nested_type(
            Record::from(name)
                .with_comment(format!(" The case: {{@code {name}}}."))
                .with_param(("value", java_type))
                .with_implements("Shape")
                .with_function(
                    Function::from(Signature::from("tagNumber").with_result(JavaPrimitive::Int))
                        .with_annotation("Override")
                        .with_access(Access::Public)
                        .with_semi(format!("return {}", index + 1)),
                ),
        );
        encode.add_switch_case(SwitchCase::from(format!("{name} {var}")).with_expression(write));
    }
    interface.add_nested_type(
        Record::from("Unrecognized")
            .with_comment(" A case the variant doesn't know.")
            .with_param(("tagNumber", JavaPrimitive::Int))
            .with_param(("bytes", bytes()))
            .with_implements("Shape"),
    );
    encode.add_switch_case(
        SwitchCase::from("Unrecognized unrecognized")
            .with_expression("out.put(unrecognized.bytes())"),
    );
    interface.add_function(
        Function::from(Signature::from("encodeTo").with_param(("out", "java.nio.ByteBuffer")))
            .with_comment(" Appends the encoding of the variant to the bytes.")
            .with_modifier(Modifier::Default)
            .with_semi("out.putShort((short) this.tagNumber())")
            .with_statement(encode),
    );

    assert_eq!(
        interface.to_code(),
        "\
/**
 * A shape.
 */
public sealed interface Shape {
    /**
     * Gets the tag number of the case.
     */
    int tagNumber();

    /**
     * Appends the encoding of the variant to the bytes.
     */
    default void encodeTo(java.nio.ByteBuffer out) {
        out.putShort((short) this.tagNumber());
        switch (this) {
            case Circle circle -> out.putDouble(circle.value());
            case Label label -> out.put(label.value().getBytes(java.nio.charset.StandardCharsets.UTF_8));
            case Unrecognized unrecognized -> out.put(unrecognized.bytes());
        }
    }

    /**
     * The case: {@code Circle}.
     */
    record Circle(double value) implements Shape {
        @Override
        public int tagNumber() {
            return 1;
        }
    }

    /**
     * The case: {@code Label}.
     */
    record Label(String value) implements Shape {
        @Override
        public int tagNumber() {
            return 2;
        }
    }

    /**
     * A case the variant doesn't know.
     */
    record Unrecognized(int tagNumber, byte[] bytes) implements Shape {}
}
"
    );
}

/// A view is an interface with a getter for each field, which every form of the type implements.
#[test]
fn view_interface() {
    let mut interface: Interface = Interface::from("PointView")
        .with_comment(" The fields of any form of a point.")
        .with_access(Access::Public);
    let mut encode: Function = Function::from(Signature::from("encode").with_result(bytes()))
        .with_comment(" Encodes the struct.")
        .with_modifier(Modifier::Default)
        .with_semi(
            "java.nio.ByteBuffer out = \
            java.nio.ByteBuffer.allocate(8).order(java.nio.ByteOrder.LITTLE_ENDIAN)",
        );
    for name in ["x", "y"] {
        interface.add_signature_dec(
            SignatureDec::from(Signature::from(name).with_result(JavaPrimitive::Int))
                .with_comment(format!(" Gets the field: {{@code {name}}}.")),
        );
        encode.add_semi(format!("out.putInt(this.{name}())"));
    }
    interface.add_function(encode.with_semi("return out.array()"));

    assert_eq!(
        interface.to_code(),
        "\
/**
 * The fields of any form of a point.
 */
public interface PointView {
    /**
     * Gets the field: {@code x}.
     */
    int x();

    /**
     * Gets the field: {@code y}.
     */
    int y();

    /**
     * Encodes the struct.
     */
    default byte[] encode() {
        java.nio.ByteBuffer out = java.nio.ByteBuffer.allocate(8).order(java.nio.ByteOrder.LITTLE_ENDIAN);
        out.putInt(this.x());
        out.putInt(this.y());
        return out.array();
    }
}
"
    );
}

/// A service is an interface with a function for each call, & a function that routes to them.
#[test]
fn service() {
    let future: JavaType = JavaType::from("java.util.concurrent.CompletableFuture");
    let interface: Interface = Interface::from("Greeter")
        .with_comment(" A greeter.")
        .with_access(Access::Public)
        .with_signature_dec(
            SignatureDec::from(
                Signature::from("greet")
                    .with_param(("request", "GreetRequest"))
                    .with_result(future.clone().with_generic("GreetResponse")),
            )
            .with_comment(" Greets the name."),
        )
        .with_function(
            Function::from(
                Signature::from("route")
                    .with_param(("service", "Greeter"))
                    .with_param(("call", "String"))
                    .with_param(("request", bytes()))
                    .with_result(future.with_generic(bytes()))
                    .with_throws("DecodeException"),
            )
            .with_comment(" Routes the encoded request of the call to the service.")
            .with_modifier(Modifier::Static)
            .with_statement(
                SwitchStatement::from("call")
                    .with_return(true)
                    .with_switch_case(SwitchCase::from("\"greet\"").with_expression(
                        "service.greet(GreetRequest.decode(request)).thenApply(GreetResponse::encode)",
                    ))
                    .with_switch_case(
                        SwitchCase::default()
                            .with_expression("throw new IllegalArgumentException(call)"),
                    ),
            ),
        );

    assert_eq!(
        interface.to_code(),
        "\
/**
 * A greeter.
 */
public interface Greeter {
    /**
     * Greets the name.
     */
    java.util.concurrent.CompletableFuture<GreetResponse> greet(GreetRequest request);

    /**
     * Routes the encoded request of the call to the service.
     */
    static java.util.concurrent.CompletableFuture<byte[]> route(Greeter service, String call, byte[] request) throws DecodeException {
        return switch (call) {
            case \"greet\" -> service.greet(GreetRequest.decode(request)).thenApply(GreetResponse::encode);
            default -> throw new IllegalArgumentException(call);
        };
    }
}
"
    );
}
