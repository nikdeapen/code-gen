#[test]
fn file() {
    let max_depth = Property::from(("MAX_DEPTH", "Int"))
        .with_comment(" The most levels a type can nest.")
        .with_access(Access::Internal)
        .with_modifier(Modifier::Const)
        .with_initializer("64");
    let user_id = Class::from("UserId")
        .with_comment(" The id of a user.")
        .with_annotation("JvmInline")
        .with_modifier(Modifier::Value)
        .with_param(("value", "UUID"));
    let file = Block::default()
        .with_literal("// DO NOT EDIT: This file was generated by the ProtoPacket compiler.")
        .with_empty_line()
        .with_literal("package com.example.types")
        .with_empty_line()
        .with_literal("import java.util.UUID")
        .with_empty_line()
        .with_statement(max_depth)
        .with_empty_line()
        .with_statement(user_id);
    assert_eq!(
        file.to_code(),
        "\
// DO NOT EDIT: This file was generated by the ProtoPacket compiler.

package com.example.types

import java.util.UUID

/**
 * The most levels a type can nest.
 */
internal const val MAX_DEPTH: Int = 64

/**
 * The id of a user.
 */
@JvmInline
value class UserId(
    val value: UUID,
)
"
    );
}

#[test]
fn struct_type() {
    let compare_to = Function::from(
        Signature::from("compareTo")
            .with_param(("other", "Point"))
            .with_result("Int"),
    )
    .with_modifier(Modifier::Override)
    .with_expression("compareValuesBy(this, other, Point::x, Point::y)");
    let encode = Function::from(Signature::from("encode").with_result("ByteArray"))
        .with_comment(" Encodes the struct.")
        .with_statement(VarInit::from((
            ("out", "ByteBuffer"),
            "ByteBuffer.allocate(ENCODED_LEN).order(ByteOrder.LITTLE_ENDIAN)",
        )))
        .with_literal("out.putInt(x)")
        .with_literal("out.putInt(y)")
        .with_literal("return out.array()");
    let encoded_len = Property::from(("ENCODED_LEN", "Int"))
        .with_comment(" The length of the encoding, in bytes.")
        .with_modifier(Modifier::Const)
        .with_initializer("8");
    let decode = Function::from(
        Signature::from("decode")
            .with_param(("bytes", "ByteArray"))
            .with_result("Point"),
    )
    .with_comment(" Decodes the struct from the `bytes`.")
    .with_statement(VarInit::from((
        ("input", "ByteBuffer"),
        "ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN)",
    )))
    .with_literal("return Point(input.getInt(0), input.getInt(4))");
    let class = Class::from("Point")
        .with_comment(" A point on a grid.")
        .with_modifier(Modifier::Data)
        .with_param(Property::from(("x", "Int")).with_modifier(Modifier::Override))
        .with_param(Property::from(("y", "Int")).with_modifier(Modifier::Override))
        .with_supertype("PointView")
        .with_supertype(KotlinType::from("Comparable").with_generic("Point"))
        .with_function(compare_to)
        .with_function(encode)
        .with_companion(
            Object::default()
                .with_property(encoded_len)
                .with_function(decode),
        );
    assert_eq!(
        class.to_code(),
        "\
/**
 * A point on a grid.
 */
data class Point(
    override val x: Int,
    override val y: Int,
) : PointView, Comparable<Point> {
    override fun compareTo(other: Point): Int = compareValuesBy(this, other, Point::x, Point::y)

    /**
     * Encodes the struct.
     */
    fun encode(): ByteArray {
        val out: ByteBuffer = ByteBuffer.allocate(ENCODED_LEN).order(ByteOrder.LITTLE_ENDIAN)
        out.putInt(x)
        out.putInt(y)
        return out.array()
    }

    companion object {
        /**
         * The length of the encoding, in bytes.
         */
        const val ENCODED_LEN: Int = 8

        /**
         * Decodes the struct from the `bytes`.
         */
        fun decode(bytes: ByteArray): Point {
            val input: ByteBuffer = ByteBuffer.wrap(bytes).order(ByteOrder.LITTLE_ENDIAN)
            return Point(input.getInt(0), input.getInt(4))
        }
    }
}
"
    );
}

#[test]
fn message_type() {
    let sizes_type = KotlinType::from("List").with_generic("Int").to_nullable();
    let with_text = Function::from(
        Signature::from("withText")
            .with_param(("text", KotlinType::from("String").to_nullable()))
            .with_result("Label"),
    )
    .with_comment(" Sets the field: `text`.")
    .with_literal("this.text = text")
    .with_literal("return this");
    let encode_to = Function::from(Signature::from("encodeTo").with_param(("out", "ByteBuffer")))
        .with_comment(" Appends the encoding of the message to the `out` bytes.")
        .with_statement(VarInit::from((
            ("text", KotlinType::from("String").to_nullable()),
            "this.text",
        )))
        .with_statement(
            IfStatement::from("text != null").with_success_statements(
                Block::default()
                    .with_literal("out.putShort(1)")
                    .with_literal("out.put(text.encodeToByteArray())"),
            ),
        )
        .with_statement(VarInit::from((("sizes", sizes_type.clone()), "this.sizes")))
        .with_statement(
            IfStatement::from("sizes != null").with_success_statements(
                Block::default()
                    .with_literal("out.putShort(2)")
                    .with_statement(
                        ForLoop::from(("size", "sizes")).with_literal("out.putInt(size)"),
                    ),
            ),
        );
    let class = Class::from("Label")
        .with_comment(" A label.")
        .with_comment("")
        .with_comment(" @property text The text of the label.")
        .with_comment(" @property sizes The sizes the label is printed in.")
        .with_modifier(Modifier::Data)
        .with_param(
            Property::from(("text", KotlinType::from("String").to_nullable()))
                .with_mutable()
                .with_initializer("null"),
        )
        .with_param(
            Property::from(("sizes", sizes_type))
                .with_mutable()
                .with_initializer("null"),
        )
        .with_function(with_text)
        .with_function(encode_to);
    assert_eq!(
        class.to_code(),
        "\
/**
 * A label.
 *
 * @property text The text of the label.
 * @property sizes The sizes the label is printed in.
 */
data class Label(
    var text: String? = null,
    var sizes: List<Int>? = null,
) {
    /**
     * Sets the field: `text`.
     */
    fun withText(text: String?): Label {
        this.text = text
        return this
    }

    /**
     * Appends the encoding of the message to the `out` bytes.
     */
    fun encodeTo(out: ByteBuffer) {
        val text: String? = this.text
        if (text != null) {
            out.putShort(1)
            out.put(text.encodeToByteArray())
        }
        val sizes: List<Int>? = this.sizes
        if (sizes != null) {
            out.putShort(2)
            for (size in sizes) {
                out.putInt(size)
            }
        }
    }
}
"
    );
}

#[test]
fn enum_type() {
    let case = |name: &str, tag_number: u16| {
        Object::from(name)
            .with_comment(format!(" The case: `{name}`."))
            .with_modifier(Modifier::Data)
            .with_supertype("Color")
            .with_property(
                Property::from(("tagNumber", "UShort"))
                    .with_modifier(Modifier::Override)
                    .with_initializer(format!("{tag_number}u")),
            )
    };
    let unrecognized = Class::from("Unrecognized")
        .with_comment(" A tag number the enum doesn't know.")
        .with_modifier(Modifier::Data)
        .with_param(Property::from(("tagNumber", "UShort")).with_modifier(Modifier::Override))
        .with_supertype("Color");
    let compare_to = Function::from(
        Signature::from("compareTo")
            .with_param(("other", "Color"))
            .with_result("Int"),
    )
    .with_modifier(Modifier::Override)
    .with_expression("tagNumber.compareTo(other.tagNumber)");
    let from_tag_number = Function::from(
        Signature::from("fromTagNumber")
            .with_param(("tagNumber", "UShort"))
            .with_result("Color"),
    )
    .with_comment(" Gets the case with the `tagNumber`.")
    .with_statement(
        WhenStatement::from("tagNumber.toInt()")
            .with_return()
            .with_when_case(WhenCase::from("1").with_expression("Red"))
            .with_when_case(WhenCase::from("2").with_expression("Green"))
            .with_when_case(WhenCase::from("else").with_expression("Unrecognized(tagNumber)")),
    );
    let interface = Interface::from("Color")
        .with_comment(" A color.")
        .with_modifier(Modifier::Sealed)
        .with_supertype(KotlinType::from("Comparable").with_generic("Color"))
        .with_property(
            Property::from(("tagNumber", "UShort")).with_comment(" Gets the tag number."),
        )
        .with_function(compare_to)
        .with_companion(Object::default().with_function(from_tag_number))
        .with_nested_type(case("Red", 1))
        .with_nested_type(case("Green", 2))
        .with_nested_type(unrecognized);
    assert_eq!(
        interface.to_code(),
        "\
/**
 * A color.
 */
sealed interface Color : Comparable<Color> {
    /**
     * Gets the tag number.
     */
    val tagNumber: UShort

    override fun compareTo(other: Color): Int = tagNumber.compareTo(other.tagNumber)

    companion object {
        /**
         * Gets the case with the `tagNumber`.
         */
        fun fromTagNumber(tagNumber: UShort): Color {
            return when (tagNumber.toInt()) {
                1 -> Red
                2 -> Green
                else -> Unrecognized(tagNumber)
            }
        }
    }

    /**
     * The case: `Red`.
     */
    data object Red : Color {
        override val tagNumber: UShort = 1u
    }

    /**
     * The case: `Green`.
     */
    data object Green : Color {
        override val tagNumber: UShort = 2u
    }

    /**
     * A tag number the enum doesn't know.
     */
    data class Unrecognized(
        override val tagNumber: UShort,
    ) : Color
}
"
    );
}

#[test]
fn variant_type() {
    let case = |name: &str, kotlin_type: &str| {
        Class::from(name)
            .with_comment(format!(" The case: `{name}`."))
            .with_modifier(Modifier::Data)
            .with_param(("value", kotlin_type))
            .with_supertype("Shape")
    };
    let unrecognized = Class::from("Unrecognized")
        .with_comment(" A case the variant doesn't know.")
        .with_modifier(Modifier::Data)
        .with_param(("tagNumber", "UShort"))
        .with_param(("bytes", "ByteArray"))
        .with_supertype("Shape");
    let encoded_len = Function::from(Signature::from("encodedLen").with_result("Int"))
        .with_comment(" Gets the length of the encoding, in bytes.")
        .with_statement(
            WhenStatement::from("this")
                .with_return()
                .with_when_case(WhenCase::from("is Circle").with_expression("10"))
                .with_when_case(
                    WhenCase::from("is Text").with_expression("2 + value.encodeToByteArray().size"),
                )
                .with_when_case(
                    WhenCase::from("is Unrecognized").with_expression("2 + bytes.size"),
                ),
        );
    let encode_to = Function::from(Signature::from("encodeTo").with_param(("out", "ByteBuffer")))
        .with_comment(" Appends the encoding of the variant to the `out` bytes.")
        .with_statement(
            WhenStatement::from("this")
                .with_when_case(
                    WhenCase::from("is Circle")
                        .with_literal("out.putShort(1)")
                        .with_literal("out.putDouble(value)"),
                )
                .with_when_case(
                    WhenCase::from("is Text")
                        .with_literal("out.putShort(2)")
                        .with_literal("out.put(value.encodeToByteArray())"),
                )
                .with_when_case(
                    WhenCase::from("is Unrecognized")
                        .with_literal("out.putShort(tagNumber.toShort())")
                        .with_literal("out.put(bytes)"),
                ),
        );
    let interface = Interface::from("Shape")
        .with_comment(" A shape.")
        .with_modifier(Modifier::Sealed)
        .with_function(encoded_len)
        .with_function(encode_to)
        .with_nested_type(case("Circle", "Double"))
        .with_nested_type(case("Text", "String"))
        .with_nested_type(unrecognized);
    assert_eq!(
        interface.to_code(),
        "\
/**
 * A shape.
 */
sealed interface Shape {
    /**
     * Gets the length of the encoding, in bytes.
     */
    fun encodedLen(): Int {
        return when (this) {
            is Circle -> 10
            is Text -> 2 + value.encodeToByteArray().size
            is Unrecognized -> 2 + bytes.size
        }
    }

    /**
     * Appends the encoding of the variant to the `out` bytes.
     */
    fun encodeTo(out: ByteBuffer) {
        when (this) {
            is Circle -> {
                out.putShort(1)
                out.putDouble(value)
            }
            is Text -> {
                out.putShort(2)
                out.put(value.encodeToByteArray())
            }
            is Unrecognized -> {
                out.putShort(tagNumber.toShort())
                out.put(bytes)
            }
        }
    }

    /**
     * The case: `Circle`.
     */
    data class Circle(
        val value: Double,
    ) : Shape

    /**
     * The case: `Text`.
     */
    data class Text(
        val value: String,
    ) : Shape

    /**
     * A case the variant doesn't know.
     */
    data class Unrecognized(
        val tagNumber: UShort,
        val bytes: ByteArray,
    ) : Shape
}
"
    );
}

#[test]
fn view_types() {
    let getter = |name: &str, offset: usize| {
        Property::from((name, "Int"))
            .with_modifier(Modifier::Override)
            .with_getter(format!("bytes.getInt({offset})"))
    };
    let view = Interface::from("PointView")
        .with_comment(" The fields of any form of a [Point].")
        .with_property(Property::from(("x", "Int")).with_comment(" Gets the field: `x`."))
        .with_property(Property::from(("y", "Int")).with_comment(" Gets the field: `y`."))
        .with_function(
            Function::from(Signature::from("encodedLen").with_result("Int"))
                .with_comment(" Gets the length of the encoding, in bytes.")
                .with_expression("8"),
        );
    let reference = Class::from("PointRef")
        .with_comment(" A [Point] that is read from its encoding.")
        .with_param(Property::from(("bytes", "ByteBuffer")).with_access(Access::Private))
        .with_supertype("PointView")
        .with_property(getter("x", 0))
        .with_property(getter("y", 4));
    let block = Block::default()
        .with_statement(view)
        .with_empty_line()
        .with_statement(reference);
    assert_eq!(
        block.to_code(),
        "\
/**
 * The fields of any form of a [Point].
 */
interface PointView {
    /**
     * Gets the field: `x`.
     */
    val x: Int

    /**
     * Gets the field: `y`.
     */
    val y: Int

    /**
     * Gets the length of the encoding, in bytes.
     */
    fun encodedLen(): Int = 8
}

/**
 * A [Point] that is read from its encoding.
 */
class PointRef(
    private val bytes: ByteBuffer,
) : PointView {
    override val x: Int
        get() = bytes.getInt(0)

    override val y: Int
        get() = bytes.getInt(4)
}
"
    );
}

#[test]
fn service() {
    let call = |name: &str, comment: &str, request: &str, response: &str| {
        SignatureDec::from(
            Signature::from(name)
                .with_param(("request", request))
                .with_result(response),
        )
        .with_comment(comment)
        .with_modifier(Modifier::Suspend)
    };
    let interface = Interface::from("Greeter")
        .with_comment(" A greeter.")
        .with_signature_dec(call(
            "greet",
            " Greets the name.",
            "GreetRequest",
            "GreetResponse",
        ))
        .with_signature_dec(call(
            "step",
            " Moves the point by one in both coordinates.",
            "Point",
            "Point",
        ));
    let route = |name: &str, request: &str| {
        WhenCase::from(format!("\"{name}\"")).with_expression(format!(
            "service.{name}({request}.decode(request)).encode()"
        ))
    };
    let router = Function::from(
        Signature::from("routeGreeter")
            .with_param(("service", "Greeter"))
            .with_param(("call", "String"))
            .with_param(("request", "ByteArray"))
            .with_result("ByteArray"),
    )
    .with_comment(" Routes the `request` of the `call` to the `service`.")
    .with_modifier(Modifier::Suspend)
    .with_statement(
        WhenStatement::from("call")
            .with_return()
            .with_when_case(route("greet", "GreetRequest"))
            .with_when_case(route("step", "Point"))
            .with_when_case(
                WhenCase::from("else")
                    .with_expression("throw IllegalArgumentException(\"unknown call: $call\")"),
            ),
    );
    let block = Block::default()
        .with_statement(interface)
        .with_empty_line()
        .with_statement(router);
    assert_eq!(
        block.to_code(),
        "\
/**
 * A greeter.
 */
interface Greeter {
    /**
     * Greets the name.
     */
    suspend fun greet(request: GreetRequest): GreetResponse

    /**
     * Moves the point by one in both coordinates.
     */
    suspend fun step(request: Point): Point
}

/**
 * Routes the `request` of the `call` to the `service`.
 */
suspend fun routeGreeter(service: Greeter, call: String, request: ByteArray): ByteArray {
    return when (call) {
        \"greet\" -> service.greet(GreetRequest.decode(request)).encode()
        \"step\" -> service.step(Point.decode(request)).encode()
        else -> throw IllegalArgumentException(\"unknown call: $call\")
    }
}
"
    );
}
