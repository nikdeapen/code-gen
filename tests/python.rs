/// A struct is a frozen dataclass, which has its constructor, equality, ordering & hashing.
#[test]
fn struct_type() {
    let encode: Function = Function::from(
        Signature::from("encode")
            .with_receiver(Receiver::Instance)
            .with_result("bytes"),
    )
    .with_comment("Encodes the point.")
    .with_literal("return _POINT.pack(self.x, self.y)");
    let decode: Function = Function::from(
        Signature::from("decode")
            .with_receiver(Receiver::Class)
            .with_param(("data", "bytes"))
            .with_result("Self"),
    )
    .with_decorator("classmethod")
    .with_comment("Decodes a point from the `data`.")
    .with_literal("x, y = _POINT.unpack(data)")
    .with_literal("return cls(x, y)");
    let class: Class = Class::from("Point")
        .with_decorator("dataclass(frozen=True, order=True, slots=True)")
        .with_comment("A point on a grid.")
        .with_field(Field::from(("x", "int")).with_comment("The distance from the left edge."))
        .with_field(Field::from(("y", "int")).with_comment("The distance from the top edge."))
        .with_function(encode)
        .with_function(decode);
    let file: Block = Block::default()
        .with_literal("# DO NOT EDIT: This file was generated by the ProtoPacket compiler.")
        .with_empty_line()
        .with_literal("import struct")
        .with_literal("from dataclasses import dataclass")
        .with_literal("from typing import Final, Self")
        .with_empty_line()
        .with_expression_statement(
            Var::from(("_POINT", "Final")).with_value("struct.Struct(\"<ii\")"),
        )
        .with_empty_line()
        .with_empty_line()
        .with_statement(class);

    let expected: &str = r#"# DO NOT EDIT: This file was generated by the ProtoPacket compiler.

import struct
from dataclasses import dataclass
from typing import Final, Self

_POINT: Final = struct.Struct("<ii")


@dataclass(frozen=True, order=True, slots=True)
class Point:
    """A point on a grid."""

    x: int
    """The distance from the left edge."""

    y: int
    """The distance from the top edge."""

    def encode(self) -> bytes:
        """Encodes the point."""
        return _POINT.pack(self.x, self.y)

    @classmethod
    def decode(cls, data: bytes) -> Self:
        """Decodes a point from the `data`."""
        x, y = _POINT.unpack(data)
        return cls(x, y)
"#;
    assert_eq!(file.to_code(), expected);
}

/// A message is a class of optional fields, with a getter & a setter for each one.
#[test]
fn message_type() {
    let fields: [(&str, PythonType, &str); 2] = [
        (
            "name",
            PythonType::from("str").to_optional(),
            "Gets the name.",
        ),
        (
            "emails",
            PythonType::from("list").with_generic("str").to_optional(),
            "Gets the email addresses.",
        ),
    ];

    let mut signature: Signature = Signature::from("__init__")
        .with_receiver(Receiver::Instance)
        .with_param("*")
        .with_result("None");
    for (name, python_type, _) in &fields {
        signature.add_param(Var::from((*name, python_type.clone())).with_value("None"));
    }
    let mut init: Function = Function::from(signature);
    for (name, python_type, _) in &fields {
        init.add_literal(format!("self._{name}: {python_type} = {name}"));
    }

    let mut class: Class = Class::from("Person")
        .with_comment("A person in an address book.")
        .with_comment("")
        .with_comment("Every field is optional.")
        .with_field(Var::from("__slots__").with_value("(\"_name\", \"_emails\")"))
        .with_function(init);
    for (name, python_type, comment) in &fields {
        let getter: Signature = Signature::from(*name)
            .with_receiver(Receiver::Instance)
            .with_result(python_type.clone());
        class.add_function(
            Function::from(getter)
                .with_decorator("property")
                .with_comment(*comment)
                .with_literal(format!("return self._{name}")),
        );
        let setter: Signature = Signature::from(*name)
            .with_receiver(Receiver::Instance)
            .with_param(("value", python_type.clone()))
            .with_result("None");
        class.add_function(
            Function::from(setter)
                .with_decorator(format!("{name}.setter"))
                .with_literal(format!("self._{name} = value")),
        );
    }

    let emails: ForLoop =
        ForLoop::from(("email", "self._emails")).with_literal("write_string(out, 2, email)");
    let encode: Function = Function::from(
        Signature::from("encode")
            .with_receiver(Receiver::Instance)
            .with_result("bytes"),
    )
    .with_comment("Encodes the person.")
    .with_literal("out = bytearray()")
    .with_statement(
        IfStatement::from("self._name is not None").with_success_statements(
            Block::default().with_literal("write_string(out, 1, self._name)"),
        ),
    )
    .with_statement(
        IfStatement::from("self._emails is not None")
            .with_success_statements(Block::default().with_statement(emails)),
    )
    .with_literal("return bytes(out)");
    class.add_function(encode);

    let expected: &str = r#"class Person:
    """A person in an address book.

    Every field is optional.
    """

    __slots__ = ("_name", "_emails")

    def __init__(self, *, name: str | None = None, emails: list[str] | None = None) -> None:
        self._name: str | None = name
        self._emails: list[str] | None = emails

    @property
    def name(self) -> str | None:
        """Gets the name."""
        return self._name

    @name.setter
    def name(self, value: str | None) -> None:
        self._name = value

    @property
    def emails(self) -> list[str] | None:
        """Gets the email addresses."""
        return self._emails

    @emails.setter
    def emails(self, value: list[str] | None) -> None:
        self._emails = value

    def encode(self) -> bytes:
        """Encodes the person."""
        out = bytearray()
        if self._name is not None:
            write_string(out, 1, self._name)
        if self._emails is not None:
            for email in self._emails:
                write_string(out, 2, email)
        return bytes(out)
"#;
    assert_eq!(class.to_code(), expected);
}

/// A message is decoded by a loop over its fields, which matches each tag number.
#[test]
fn message_decoding() {
    let fields: [(u16, &str); 2] = [
        (1, "person.name, offset = read_string(data, offset)"),
        (2, "person.emails, offset = read_strings(data, offset)"),
    ];

    let mut field: MatchStatement = MatchStatement::from("tag_number");
    for (tag_number, read) in fields {
        field.add_match_case(MatchCase::from(tag_number.to_string()).with_literal(read));
    }
    field.add_match_case(MatchCase::from("_").with_literal("offset = skip_value(data, offset)"));
    let decode: Function = Function::from(
        Signature::from("decode_person")
            .with_param(("data", "bytes"))
            .with_result("Person"),
    )
    .with_comment("Decodes a person from the `data`.")
    .with_literal("person = Person()")
    .with_literal("offset = 0")
    .with_statement(
        WhileLoop::from("offset < len(data)")
            .with_literal("tag_number, offset = read_tag_number(data, offset)")
            .with_statement(field),
    )
    .with_literal("return person");

    let expected: &str = r#"def decode_person(data: bytes) -> Person:
    """Decodes a person from the `data`."""
    person = Person()
    offset = 0
    while offset < len(data):
        tag_number, offset = read_tag_number(data, offset)
        match tag_number:
            case 1:
                person.name, offset = read_string(data, offset)
            case 2:
                person.emails, offset = read_strings(data, offset)
            case _:
                offset = skip_value(data, offset)
    return person
"#;
    assert_eq!(decode.to_code(), expected);
}

/// An enum is a class with a constant for each case, since an `Enum` can't hold an unrecognized
/// tag number.
#[test]
fn enum_type() {
    let cases: [(&str, u16, &str); 2] = [
        ("RED", 1, "The light to stop."),
        ("GREEN", 2, "The light to go."),
    ];

    let mut class: Class = Class::from("Color")
        .with_decorator("dataclass(frozen=True, order=True, slots=True)")
        .with_comment("A color of a traffic light.")
        .with_comment("")
        .with_comment("A tag number with no case is an unrecognized color.")
        .with_field(("tag_number", "int"));
    for (name, _, comment) in cases {
        let python_type: PythonType = PythonType::from("ClassVar").with_generic("Color");
        class.add_field(Field::from((name, python_type)).with_comment(comment));
    }
    let tag_numbers: Vec<String> = cases
        .iter()
        .map(|(_, tag_number, _)| tag_number.to_string())
        .collect();
    class.add_function(
        Function::from(
            Signature::from("is_unrecognized")
                .with_receiver(Receiver::Instance)
                .with_result("bool"),
        )
        .with_decorator("property")
        .with_comment("Checks if the tag number has no case.")
        .with_literal(format!(
            "return self.tag_number not in ({})",
            tag_numbers.join(", ")
        )),
    );
    let mut file: Block = Block::default()
        .with_literal("from __future__ import annotations")
        .with_empty_line()
        .with_literal("from dataclasses import dataclass")
        .with_literal("from typing import ClassVar")
        .with_empty_line()
        .with_empty_line()
        .with_statement(class)
        .with_empty_line()
        .with_empty_line();
    for (name, tag_number, _) in cases {
        file.add_literal(format!("Color.{name} = Color({tag_number})"));
    }

    let expected: &str = r#"from __future__ import annotations

from dataclasses import dataclass
from typing import ClassVar


@dataclass(frozen=True, order=True, slots=True)
class Color:
    """A color of a traffic light.

    A tag number with no case is an unrecognized color.
    """

    tag_number: int

    RED: ClassVar[Color]
    """The light to stop."""

    GREEN: ClassVar[Color]
    """The light to go."""

    @property
    def is_unrecognized(self) -> bool:
        """Checks if the tag number has no case."""
        return self.tag_number not in (1, 2)


Color.RED = Color(1)
Color.GREEN = Color(2)
"#;
    assert_eq!(file.to_code(), expected);
}

/// A variant is a union of a dataclass for each case, plus one for an unrecognized case.
#[test]
fn variant_type() {
    let cases: [(&str, u16, &str); 2] = [
        ("Circle", 1, "A round shape."),
        ("Square", 2, "A shape with four equal sides."),
    ];

    let mut file: Block = Block::default();
    let mut union: Vec<PythonType> = Vec::default();
    let mut encode: MatchStatement = MatchStatement::from("shape");
    for (name, tag_number, comment) in cases {
        let case_name: String = format!("Shape{name}");
        file.add_statement(
            Class::from(case_name.as_str())
                .with_decorator("dataclass(frozen=True, slots=True)")
                .with_comment(comment)
                .with_field(("value", name)),
        );
        file.add_empty_line();
        file.add_empty_line();
        encode.add_match_case(
            MatchCase::from(format!("{case_name}(value)"))
                .with_literal(format!("return write_case({tag_number}, value.encode())")),
        );
        union.push(case_name.into());
    }
    file.add_statement(
        Class::from("ShapeUnrecognized")
            .with_decorator("dataclass(frozen=True, slots=True)")
            .with_comment("A case the variant doesn't know.")
            .with_field(("tag_number", "int"))
            .with_field(("data", "bytes")),
    );
    file.add_empty_line();
    file.add_empty_line();
    encode.add_match_case(
        MatchCase::from("ShapeUnrecognized(tag_number, data)")
            .with_literal("return write_case(tag_number, data)"),
    );
    union.push("ShapeUnrecognized".into());
    file.add_statement(TypeDec::from(("Shape", PythonType::Union(union))).with_comment("A shape."));
    file.add_empty_line();
    file.add_empty_line();
    file.add_statement(
        Function::from(
            Signature::from("encode_shape")
                .with_param(("shape", "Shape"))
                .with_result("bytes"),
        )
        .with_comment("Encodes the `shape`.")
        .with_statement(encode),
    );

    let expected: &str = r#"@dataclass(frozen=True, slots=True)
class ShapeCircle:
    """A round shape."""

    value: Circle


@dataclass(frozen=True, slots=True)
class ShapeSquare:
    """A shape with four equal sides."""

    value: Square


@dataclass(frozen=True, slots=True)
class ShapeUnrecognized:
    """A case the variant doesn't know."""

    tag_number: int
    data: bytes


type Shape = ShapeCircle | ShapeSquare | ShapeUnrecognized
"""A shape."""


def encode_shape(shape: Shape) -> bytes:
    """Encodes the `shape`."""
    match shape:
        case ShapeCircle(value):
            return write_case(1, value.encode())
        case ShapeSquare(value):
            return write_case(2, value.encode())
        case ShapeUnrecognized(tag_number, data):
            return write_case(tag_number, data)
"#;
    assert_eq!(file.to_code(), expected);
}

/// A view is a protocol with a getter for each field, which every form of the type has.
#[test]
fn view_interface() {
    let fields: [(&str, usize, &str); 2] = [
        ("x", 0, "Gets the distance from the left edge."),
        ("y", 4, "Gets the distance from the top edge."),
    ];

    let mut view: Class = Class::from("PointView")
        .with_base("Protocol")
        .with_comment("The fields of any form of a point.");
    let mut point_ref: Class = Class::from("PointRef")
        .with_comment("A point that reads its fields from its encoded bytes.")
        .with_field(Var::from("__slots__").with_value("(\"_data\",)"))
        .with_function(
            Function::from(
                Signature::from("__init__")
                    .with_receiver(Receiver::Instance)
                    .with_param(("data", "memoryview"))
                    .with_result("None"),
            )
            .with_literal("self._data = data"),
        );
    for (name, offset, comment) in fields {
        let getter: Signature = Signature::from(name)
            .with_receiver(Receiver::Instance)
            .with_result("int");
        view.add_signature_dec(
            SignatureDec::from(getter.clone())
                .with_decorator("property")
                .with_comment(comment),
        );
        point_ref.add_function(
            Function::from(getter)
                .with_decorator("property")
                .with_literal(format!(
                    "return int.from_bytes(self._data[{}:{}], \"little\", signed=True)",
                    offset,
                    offset + 4
                )),
        );
    }
    let file: Block = Block::default()
        .with_statement(view)
        .with_empty_line()
        .with_empty_line()
        .with_statement(point_ref);

    let expected: &str = r#"class PointView(Protocol):
    """The fields of any form of a point."""

    @property
    def x(self) -> int:
        """Gets the distance from the left edge."""
        ...

    @property
    def y(self) -> int:
        """Gets the distance from the top edge."""
        ...


class PointRef:
    """A point that reads its fields from its encoded bytes."""

    __slots__ = ("_data",)

    def __init__(self, data: memoryview) -> None:
        self._data = data

    @property
    def x(self) -> int:
        return int.from_bytes(self._data[0:4], "little", signed=True)

    @property
    def y(self) -> int:
        return int.from_bytes(self._data[4:8], "little", signed=True)
"#;
    assert_eq!(file.to_code(), expected);
}

/// A service is a protocol with an `async` function for each call, plus a function that routes a
/// request to its call.
#[test]
fn service() {
    let calls: [(&str, &str, &str, Option<&str>); 2] = [
        (
            "greet",
            "GreetRequest",
            "GreetResponse",
            Some("Greets a person."),
        ),
        ("part", "PartRequest", "PartResponse", None),
    ];

    let mut protocol: Class = Class::from("Greeter")
        .with_base("Protocol")
        .with_comment("A service that greets people.");
    let mut route: Function = Function::from(
        Signature::from("route_greeter")
            .with_async(true)
            .with_param(("service", "Greeter"))
            .with_param(("call", "str"))
            .with_param(("request", "bytes"))
            .with_result("bytes"),
    )
    .with_comment("Routes the `request` to the `call` of the `service`.");
    for (name, request, response, comment) in calls {
        let mut signature_dec: SignatureDec = SignatureDec::from(
            Signature::from(name)
                .with_async(true)
                .with_receiver(Receiver::Instance)
                .with_param(("request", request))
                .with_result(response),
        );
        if let Some(comment) = comment {
            signature_dec.add_comment(comment);
        }
        protocol.add_signature_dec(signature_dec);
        route.add_statement(
            IfStatement::from(format!("call == \"{name}\"")).with_success_statements(
                Block::default().with_literal(format!(
                    "return (await service.{name}({request}.decode(request))).encode()"
                )),
            ),
        );
    }
    route.add_literal("raise UnknownCallError(call)");
    let file: Block = Block::default()
        .with_statement(protocol)
        .with_empty_line()
        .with_empty_line()
        .with_statement(route);

    let expected: &str = r#"class Greeter(Protocol):
    """A service that greets people."""

    async def greet(self, request: GreetRequest) -> GreetResponse:
        """Greets a person."""
        ...

    async def part(self, request: PartRequest) -> PartResponse: ...


async def route_greeter(service: Greeter, call: str, request: bytes) -> bytes:
    """Routes the `request` to the `call` of the `service`."""
    if call == "greet":
        return (await service.greet(GreetRequest.decode(request))).encode()
    if call == "part":
        return (await service.part(PartRequest.decode(request))).encode()
    raise UnknownCallError(call)
"#;
    assert_eq!(file.to_code(), expected);
}
